// Generates the typed API client schema from the backend's OpenAPI document.
//
//   npm run gen:api                       fetch http://localhost:5080/openapi/v1.json (start the API first), then generate
//   OPENAPI_URL=https://host/openapi/v1.json npm run gen:api
//   OPENAPI_FILE=openapi/v1.json npm run gen:api   generate from the committed snapshot without a running API
//
// Writes openapi/v1.json (snapshot, committed) and src/lib/api/schema.d.ts (generated types, committed).
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const snapshot = resolve(root, "openapi/v1.json");
const output = resolve(root, "src/lib/api/schema.d.ts");
const url = process.env.OPENAPI_URL ?? "http://localhost:5080/openapi/v1.json";

mkdirSync(dirname(snapshot), { recursive: true });
mkdirSync(dirname(output), { recursive: true });

if (!process.env.OPENAPI_FILE) {
  console.log(`Fetching ${url}`);
  const response = await fetch(url).catch((error) => {
    console.error(`Could not reach ${url}: ${error.cause?.code ?? error.message}`);
    console.error("Start the API (dotnet run --project juvo-be/src/Juvo.Api) or set OPENAPI_FILE to use the snapshot.");
    process.exit(1);
  });
  if (!response.ok) {
    console.error(`${url} answered ${response.status}`);
    process.exit(1);
  }
  const document = await response.json();
  // Pretty, stable key order so the snapshot diffs well.
  writeFileSync(snapshot, JSON.stringify(document, null, 2) + "\n");
  console.log(`Saved ${Object.keys(document.paths ?? {}).length} paths to openapi/v1.json`);
}

const input = process.env.OPENAPI_FILE ? resolve(root, process.env.OPENAPI_FILE) : snapshot;
JSON.parse(readFileSync(input, "utf8")); // fail early on a broken file

const run = spawnSync(process.execPath, [resolve(root, "node_modules/openapi-typescript/bin/cli.js"), input, "-o", output], {
  stdio: "inherit",
});
if (run.status !== 0) process.exit(run.status ?? 1);

const header = "// GENERATED by `npm run gen:api` from openapi/v1.json (the API's OpenAPI document). Do not edit by hand.\n";
const generated = readFileSync(output, "utf8");
if (!generated.startsWith(header)) writeFileSync(output, header + generated);
console.log("Wrote src/lib/api/schema.d.ts");
