"""Generate brand tokens (CSS + docs) from the logo palette and check WCAG AA contrast.

Usage: python -I -X utf8 scripts/generate_tokens.py

Logo colours come from scripts/extract_palette.py run on Logo/Official Logo.jpg:
  swoosh red #DB0100, background reds #C5281F..#821210, inner disc ink #1C0807,
  J and ring cream #EBE5DB..#F0E8DD.
Only neutrals and status colours are tuned for contrast; logo colours are used as sampled.
Writes: juvo-front/src/styles/tokens.css, docs/brand-tokens.md (+ copies for each project's docs).
Fails (exit 1) if any text pair is below 4.5:1 (3:1 for large/UI-only pairs).
"""
